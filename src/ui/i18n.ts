export const DICTS: Record<Language, Dict> = { en, ar };

export type Translate = (key: string, params?: Record<string, string | number>) => string;

export function makeT(lang: Language): Translate {
  const d = DICTS[lang];
  return (key, params) => {
    let s = d[key] ?? en[key] ?? key;
    if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export const I18nContext = createContext<{ lang: Language; t: Translate }>({ lang: 'ar', t: makeT('ar') });

export const useI18n = (): { lang: Language; t: Translate } => useContext(I18nContext);
